// Builds src/commands.gen.ts, the vehicle and energy command catalog, from the
// live public spec so integrations can offer every command without a wrapper.

import { writeFile } from "node:fs/promises";
import type { CommandField, CommandSpec } from "../src/commands.js";
import { fetchPublicSpec, packageRoot } from "./spec.js";

const VEHICLE_PREFIXES = ["/api/1/vehicles/{vin}/command/", "/api/1/vehicles/{vin}/custom_command/"];
const ENERGY_PREFIX = "/api/1/energy_sites/{id}/";

// Factory-reset-like, key-removing and raw passthrough routes integrations must not offer.
const DENY = new Set([
  "erase_user_data",
  "remove_key",
  "command",
  "add_authorized_client",
  "remove_authorized_client",
  "set_local_site_config",
]);

const SENSITIVE = /pin|password/i;

function field(name: string, schema: any, required: boolean): CommandField {
  const out: CommandField = { name };
  switch (schema.type) {
    case "integer":
      out.type = "number";
      out.integer = true;
      break;
    case "number":
    case "string":
    case "boolean":
      out.type = schema.type;
      break;
    case "object":
      out.type = "object";
      break;
    case "array":
      out.type = "object";
      out.isArray = true;
      break;
    // oneOf/anyOf unions take any JSON value.
  }
  if (schema.minimum !== undefined) out.min = schema.minimum;
  if (schema.maximum !== undefined) out.max = schema.maximum;
  if (schema.enum) out.enum = schema.enum.map(String);
  if (required) out.required = true;
  if (schema.default !== undefined) out.default = schema.default;
  if (schema.description) out.description = schema.description;
  if (SENSITIVE.test(name)) out.sensitive = true;
  return out;
}

function command(path: string, method: "get" | "post", op: any, hasPost: boolean): CommandSpec | undefined {
  const route = path.split("/").pop()!;
  if (DENY.has(route)) return;
  const params: any[] = op.parameters ?? [];
  if (params.some((p) => p.in === "query" && p.required)) return;

  const body = op.requestBody?.content?.["application/json"]?.schema;
  const required = new Set<string>(body?.required ?? []);
  const description: string = op.description ?? "";
  const spec: CommandSpec = {
    name: method === "get" && hasPost ? `get_${route}` : route,
    label: op.summary ?? route,
    group: op.tags?.[0] ?? "Other",
    method: method === "get" ? "GET" : "POST",
    path,
    fields: Object.entries(body?.properties ?? {}).map(([name, schema]) =>
      field(name, schema, required.has(name)),
    ),
  };
  const badge = op["x-badges"]?.[0]?.name;
  if (badge) spec.badge = badge;
  // Until the spec marks these as data, they are only stated in the description.
  if (description.includes("energy_site_not_paired")) spec.paired = true;
  if (/\bCybertruck\b/.test(description)) spec.models = ["Cybertruck"];
  return spec;
}

function catalog(paths: Record<string, any>, match: (path: string) => boolean): Record<string, CommandSpec> {
  const out: Record<string, CommandSpec> = {};
  for (const path of Object.keys(paths).filter(match).sort()) {
    const item = paths[path];
    for (const method of ["post", "get"] as const) {
      if (!item[method]) continue;
      const spec = command(path, method, item[method], !!item.post);
      if (!spec) continue;
      if (out[spec.name]) throw new Error(`duplicate command name ${spec.name} (${path})`);
      out[spec.name] = spec;
    }
  }
  return out;
}

const spec = await fetchPublicSpec();
const vehicle = catalog(spec.paths, (p) => VEHICLE_PREFIXES.some((prefix) => p.startsWith(prefix)));
const energy = catalog(spec.paths, (p) => p.startsWith(ENERGY_PREFIX));

const source = `// This file is auto-generated by scripts/generate-command-catalog.ts from the public OpenAPI spec. Do not edit.
import type { CommandSpec } from "./commands.js";

export const VEHICLE_COMMANDS: Record<string, CommandSpec> = ${JSON.stringify(vehicle, null, 2)};

export const ENERGY_COMMANDS: Record<string, CommandSpec> = ${JSON.stringify(energy, null, 2)};
`;

await writeFile(`${packageRoot}src/commands.gen.ts`, source);
console.log(
  `Wrote ${Object.keys(vehicle).length} vehicle and ${Object.keys(energy).length} energy commands to src/commands.gen.ts`,
);
